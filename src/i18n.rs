use std::env;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    English,
    SimplifiedChinese,
}

impl Language {
    pub const ALL: [Self; 2] = [Self::English, Self::SimplifiedChinese];

    pub fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::SimplifiedChinese => "zh-CN",
        }
    }

    pub fn english_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::SimplifiedChinese => "Simplified Chinese",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::SimplifiedChinese => "简体中文",
        }
    }

    pub fn display_name(self, ui_language: Language) -> &'static str {
        match ui_language {
            Language::English => self.english_name(),
            Language::SimplifiedChinese => self.native_name(),
        }
    }

    pub fn from_code(value: &str) -> Option<Self> {
        let value = value.trim().replace('_', "-").to_ascii_lowercase();
        let value = value.split('.').next().unwrap_or(&value);
        match value {
            "en" | "en-us" | "en-gb" | "english" => Some(Self::English),
            "zh" | "zh-cn" | "zh-hans" | "cn" | "chinese" | "simplified-chinese" => {
                Some(Self::SimplifiedChinese)
            }
            _ => None,
        }
    }

    pub fn tr(self, message: Message) -> &'static str {
        translate(self, message)
    }
}

pub fn configured(setting: Option<&str>) -> Language {
    setting.and_then(Language::from_code).unwrap_or_else(detect)
}

pub fn detect() -> Language {
    ["STARAIL_LANG", "LC_ALL", "LC_MESSAGES", "LANG"]
        .iter()
        .filter_map(|key| env::var(key).ok())
        .find_map(|value| Language::from_code(&value))
        .unwrap_or(Language::English)
}

