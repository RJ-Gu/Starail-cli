#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_supported_language_codes() {
        assert_eq!(Language::from_code("en"), Some(Language::English));
        assert_eq!(
            Language::from_code("zh_CN.UTF-8"),
            Some(Language::SimplifiedChinese)
        );
        assert_eq!(
            Language::from_code("zh-Hans"),
            Some(Language::SimplifiedChinese)
        );
        assert_eq!(Language::from_code("fr"), None);
    }

    #[test]
    fn translates_messages() {
        assert_eq!(Language::English.tr(Message::Settings), "Settings");
        assert_eq!(Language::SimplifiedChinese.tr(Message::Settings), "设置");
    }
}
